"""Generate a compile-on-demand VEGAS script for a batch of timeline ops.

Used when the live TCP host cannot be reached and the caller still wants
VEGAS to apply an edit. VEGAS Pro 22 runs the script via /RUNSCRIPT; there
is no documented no-UI mode, so the GUI still opens.

The generated script reads a sibling .job.json (avoids SCRIPTARGS overload
ambiguity) and implements a small, explicit op set.
"""
from __future__ import annotations

import json
import os
import tempfile
from typing import Any

ONESHOT_CS = r'''// Generated by Rushcut oneshot. Do not edit by hand.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Windows.Forms;
using ScriptPortal.Vegas;

public class EntryPoint
{
    Vegas vegas;

    public void FromVegas(Vegas vegas)
    {
        this.vegas = vegas;
        string jobPath = Path.ChangeExtension(ScriptPortal.Vegas.Script.File, ".json");
        if (!File.Exists(jobPath))
        {
            MessageBox.Show("oneshot job JSON missing: " + jobPath, "Rushcut MCP");
            return;
        }
        string json = File.ReadAllText(jobPath);
        string err = null;
        try { err = RunJob(json); }
        catch (Exception ex) { err = ex.Message; }
        string resultPath = Path.ChangeExtension(jobPath, ".result.json");
        File.WriteAllText(resultPath, err == null
            ? "{\"ok\":true}"
            : "{\"ok\":false,\"error\":\"" + esc(err) + "\"}");
        if (Has(json, "exit") && GetBool(json, "exit", false))
            vegas.Exit();
    }

    string RunJob(string json)
    {
        string open = GetStr(json, "open");
        if (open != null && open.Length > 0)
        {
            if (!File.Exists(open)) return "open path not found: " + open;
            vegas.NewProject(false, false);
            if (!vegas.OpenProject(open)) return "OpenProject failed: " + open;
        }
        string ops = GetArray(json, "ops") ?? "[]";
        List<string> items = EnumObjs(ops);
        foreach (string op in items)
        {
            string name = GetStr(op, "op") ?? "";
            string fail = Apply(name, op);
            if (fail != null) return fail;
        }
        string save = GetStr(json, "save");
        if (save != null && save.Length > 0)
        {
            if (!vegas.SaveProject(save)) return "SaveProject failed: " + save;
        }
        return null;
    }

    string Apply(string name, string op)
    {
        Project p = vegas.Project;
        if (name == "add_track")
        {
            string type = (GetStr(op, "type") ?? "video").ToLowerInvariant();
            string nm = GetStr(op, "name") ?? "";
            int index = GetInt(op, "index", p.Tracks.Count);
            if (type == "audio") p.Tracks.Add(new AudioTrack(p, index, nm));
            else p.Tracks.Add(new VideoTrack(p, index, nm));
            return null;
        }
        if (name == "set_video")
        {
            int w = GetInt(op, "width", 0); int h = GetInt(op, "height", 0);
            if (w > 0) p.Video.Width = w;
            if (h > 0) p.Video.Height = h;
            double fps = GetDouble(op, "frame_rate", double.NaN);
            if (!double.IsNaN(fps)) p.Video.FrameRate = fps;
            return null;
        }
        if (name == "place_media" || name == "add_video" || name == "add_audio")
        {
            string path = GetStr(op, "path") ?? GetStr(op, "media_path");
            if (path == null || !File.Exists(path)) return "media not found: " + path;
            int ti = GetInt(op, "track_index", -1);
            if (ti < 0 || ti >= p.Tracks.Count) return "bad track_index";
            Track t = p.Tracks[ti];
            Media m = p.MediaPool.AddMedia(path);
            double start = GetDouble(op, "start_seconds", 0);
            double len = GetDouble(op, "length_seconds", -1);
            Timecode st = Timecode.FromSeconds(start);
            Timecode ln = len > 0 ? Timecode.FromSeconds(len) : m.Length;
            if (t.IsVideo())
            {
                VideoEvent ev = new VideoEvent(st, ln);
                t.Events.Add(ev);
                ev.Takes.Add(new Take(m.GetVideoStreamByIndex(0)));
            }
            else
            {
                AudioEvent ev = new AudioEvent(st, ln);
                t.Events.Add(ev);
                ev.Takes.Add(new Take(m.GetAudioStreamByIndex(0)));
            }
            return null;
        }
        if (name == "set_fades")
        {
            TrackEvent ev = GetEv(p, op);
            if (ev == null) return "set_fades: missing event";
            double fi = GetDouble(op, "fade_in_seconds", double.NaN);
            double fo = GetDouble(op, "fade_out_seconds", double.NaN);
            if (!double.IsNaN(fi)) ev.FadeIn.Length = Timecode.FromSeconds(fi);
            if (!double.IsNaN(fo)) ev.FadeOut.Length = Timecode.FromSeconds(fo);
            return null;
        }
        if (name == "move_event")
        {
            TrackEvent ev = GetEv(p, op);
            if (ev == null) return "move_event: missing event";
            ev.Start = Timecode.FromSeconds(GetDouble(op, "start_seconds", 0));
            return null;
        }
        if (name == "trim_event")
        {
            TrackEvent ev = GetEv(p, op);
            if (ev == null) return "trim_event: missing event";
            double st = GetDouble(op, "start_seconds", double.NaN);
            double ln = GetDouble(op, "length_seconds", double.NaN);
            if (!double.IsNaN(st)) ev.Start = Timecode.FromSeconds(st);
            if (!double.IsNaN(ln)) ev.Length = Timecode.FromSeconds(ln);
            return null;
        }
        return "unsupported oneshot op: " + name;
    }

    TrackEvent GetEv(Project p, string op)
    {
        int ti = GetInt(op, "track_index", -1);
        int ei = GetInt(op, "event_index", -1);
        if (ti < 0 || ti >= p.Tracks.Count) return null;
        if (ei < 0 || ei >= p.Tracks[ti].Events.Count) return null;
        return p.Tracks[ti].Events[ei];
    }

    static string esc(string s) { return (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\""); }
    static bool Has(string json, string key) { return json.IndexOf("\"" + key + "\"") >= 0; }
    static string GetStr(string json, string key)
    {
        string m = "\"" + key + "\":";
        int i = json.IndexOf(m);
        if (i < 0) return null;
        i += m.Length;
        while (i < json.Length && char.IsWhiteSpace(json[i])) i++;
        if (i < json.Length && json[i] == '"')
        {
            int j = i + 1;
            while (j < json.Length && json[j] != '"') { if (json[j] == '\\') j++; j++; }
            return json.Substring(i + 1, j - i - 1);
        }
        int k = i;
        while (k < json.Length && json[k] != ',' && json[k] != '}' && json[k] != ']') k++;
        string raw = json.Substring(i, k - i).Trim();
        return raw == "null" ? null : raw;
    }
    static int GetInt(string json, string key, int fb)
    {
        string s = GetStr(json, key);
        int v; return (s != null && int.TryParse(s.Trim('"'), out v)) ? v : fb;
    }
    static double GetDouble(string json, string key, double fb)
    {
        string s = GetStr(json, key);
        double v; return (s != null && double.TryParse(s.Trim('"'), NumberStyles.Float, CultureInfo.InvariantCulture, out v)) ? v : fb;
    }
    static bool GetBool(string json, string key, bool fb)
    {
        string s = GetStr(json, key);
        if (s == null) return fb;
        s = s.Trim().Trim('"').ToLowerInvariant();
        if (s == "true" || s == "1") return true;
        if (s == "false" || s == "0") return false;
        return fb;
    }
    static string GetArray(string json, string key)
    {
        string m = "\"" + key + "\":";
        int i = json.IndexOf(m);
        if (i < 0) return null;
        i += m.Length;
        while (i < json.Length && char.IsWhiteSpace(json[i])) i++;
        if (i >= json.Length || json[i] != '[') return null;
        int d = 0, start = i;
        for (; i < json.Length; i++)
        {
            if (json[i] == '[') d++;
            else if (json[i] == ']') { d--; if (d == 0) return json.Substring(start, i - start + 1); }
        }
        return null;
    }
    static List<string> EnumObjs(string arr)
    {
        List<string> list = new List<string>();
        int i = 0;
        while (i < arr.Length && arr[i] != '[') i++;
        i++;
        while (i < arr.Length)
        {
            while (i < arr.Length && (char.IsWhiteSpace(arr[i]) || arr[i] == ',')) i++;
            if (i >= arr.Length || arr[i] == ']') break;
            if (arr[i] != '{') { i++; continue; }
            int d = 0, start = i;
            for (; i < arr.Length; i++)
            {
                if (arr[i] == '{') d++;
                else if (arr[i] == '}') { d--; if (d == 0) { list.Add(arr.Substring(start, i - start + 1)); i++; break; } }
            }
        }
        return list;
    }
}
'''


def write_oneshot_job(job: dict[str, Any], dest_dir: str | None = None) -> dict[str, Any]:
    dest = dest_dir or tempfile.mkdtemp(prefix="rushcut-oneshot-")
    os.makedirs(dest, exist_ok=True)
    stem = os.path.join(dest, "job")
    cs_path = stem + ".cs"
    json_path = stem + ".json"
    with open(cs_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(ONESHOT_CS)
    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(job, fh, indent=2)
    return {"ok": True, "script_path": cs_path, "job_path": json_path, "result_path": stem + ".result.json"}
